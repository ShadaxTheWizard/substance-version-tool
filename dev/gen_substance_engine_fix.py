"""Write the patch table of painter/substance_engine_fix.c for a libsubstance_sse2_blend.so.

Painter 12.0.1's CPU Substance engine (libsubstance_sse2_blend.so) has functions whose
16-byte stack slots sit 8 bytes off alignment, so their aligned SSE moves (movaps) fault:
Painter crashes as soon as such a function runs, e.g. for the preview of the fabric_felt
material in a fill's properties.  The fix turns every movaps with a stack-relative operand
into movups (same encoding length, no alignment requirement).  This script lists those
instructions; it needs objdump (binutils).

    python3 dev/gen_substance_engine_fix.py "$PAINTER_DIR/libsubstance_sse2_blend.so" \
        painter/substance_engine_fix_12.0.1.h
"""
import hashlib
import re
import subprocess
import sys

MOVAPS = re.compile(r'\s*([0-9a-f]+):\t((?:[0-9a-f]{2} )+)\s*\tmovaps\s+(.*)$')


def sites(lib):
    data = open(lib, 'rb').read()
    dis = subprocess.run(['objdump', '-d', lib], capture_output=True, text=True, check=True).stdout
    out = []
    for line in dis.splitlines():
        m = MOVAPS.match(line)
        if not m or '%rsp' not in m.group(3):
            continue
        addr, raw = int(m.group(1), 16), bytes.fromhex(m.group(2).replace(' ', ''))
        i = 0
        while 0x40 <= raw[i] <= 0x4f:          # REX prefix
            i += 1
        if raw[i] != 0x0f or raw[i + 1] not in (0x28, 0x29):
            raise SystemExit(f'unexpected movaps encoding at {addr:#x}: {raw.hex()}')
        pos = addr + i + 1                     # the text segment's file offset equals its address
        if data[pos] != raw[i + 1]:
            raise SystemExit(f'file offset and address differ at {addr:#x}')
        out.append((pos, raw[i + 1]))
    return data, out


def main():
    lib, header = sys.argv[1:3]
    data, found = sites(lib)
    rows = lambda vals, n: ',\n'.join('    ' + ', '.join(vals[i:i + n]) for i in range(0, len(vals), n))
    with open(header, 'w') as f:
        f.write(f'/* Generated by dev/gen_substance_engine_fix.py from libsubstance_sse2_blend.so\n'
                f'   (size {len(data)}, sha256 {hashlib.sha256(data).hexdigest()}).\n'
                f'   File offsets of the opcode byte of each stack-relative movaps, and that byte. */\n'
                f'#define SBS_LIB_SIZE {len(data)}\n#define SBS_SITES {len(found)}\n'
                f'static const unsigned int sbs_site[SBS_SITES] = {{\n'
                f'{rows([f"0x{o:x}" for o, _ in found], 10)}\n}};\n'
                f'static const unsigned char sbs_op[SBS_SITES] = {{\n'
                f'{rows([f"0x{b:x}" for _, b in found], 16)}\n}};\n')
    print(f'{header}: {len(found)} sites')


if __name__ == '__main__':
    main()
